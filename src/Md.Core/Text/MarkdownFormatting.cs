namespace Md.Core.Text;

/// <summary>One formatting command (docs/formatting.md). <see cref="HeadingCycle"/> is the phone bar's; the desktop menus use the six levels.</summary>
public enum FormatOp
{
    Bold,
    Italic,
    Code,
    Strikethrough,
    Link,
    Heading1,
    Heading2,
    Heading3,
    Heading4,
    Heading5,
    Heading6,
    HeadingCycle,
    BulletList,
    TaskList,
    Quote,
    Indent,
    Outdent,
}

/// <summary>
/// One formatting edit: replace <c>[Start, End)</c> of the <b>original</b> text with
/// <see cref="Text"/>, then select <c>[SelectionStart, SelectionEnd)</c> of the <b>resulting</b> text.
/// </summary>
public readonly record struct FormatEdit(int Start, int End, string Text, int SelectionStart, int SelectionEnd)
{
    /// <summary>The text after the edit.</summary>
    public string ApplyTo(string original)
    {
        ArgumentNullException.ThrowIfNull(original);
        return string.Concat(original.AsSpan(0, Start), Text, original.AsSpan(End));
    }
}

/// <summary>
/// md's formatting commands — Bold, Italic, Code, Strikethrough, Link, Heading 1–6, Bullet List,
/// Task List, Quote, Indent, Outdent — and the wrap a typed <c>* _ ` $</c> makes of a selection,
/// as two pure functions over UTF-16 offsets.
/// </summary>
/// <remarks>
/// <para>
/// The specification is <c>docs/formatting.md</c>; the oracle is
/// <c>tests/Md.Core.Tests/Fixtures/formatting-vectors.json</c>, generated by the TypeScript reference
/// in <c>tools/formatting-reference/</c> and copied verbatim into md, md.macOS and md.Android. This
/// is a line-for-line port of that reference: no port may diverge from a vector, and a disputed one
/// is changed in the reference first.
/// </para>
/// <para>
/// A line break is U+000A only — the editor's adapter swaps the TextBox's CR one unit for one, as
/// SmartTyping's does. "Blank" is SP, TAB and LF and nothing else, never <c>char.IsWhiteSpace</c>.
/// Nothing here is shared with <see cref="SmartTyping"/>, which this feature does not touch.
/// </para>
/// </remarks>
public static class MarkdownFormatting
{
    const char SP = ' ';
    const char TAB = '\t';
    const char LF = '\n';

    static bool IsBlankUnit(char c) => c is SP or TAB or LF;

    /// <summary>The edit <paramref name="op"/> makes of the selection, or null for none (nothing on the undo stack).</summary>
    public static FormatEdit? Format(string text, int selectionStart, int selectionEnd, FormatOp op)
    {
        ArgumentNullException.ThrowIfNull(text);
        var (s, e) = selectionStart <= selectionEnd ? (selectionStart, selectionEnd) : (selectionEnd, selectionStart);
        if (s < 0 || e > text.Length) throw new ArgumentOutOfRangeException(nameof(selectionStart), "Selection outside the text");
        return op switch
        {
            FormatOp.Bold => Inline(text, s, e, '*', 2, (a, b) => a >= 2 && b >= 2, 2, null),
            FormatOp.Italic => Inline(text, s, e, '*', 1, (a, b) => a % 2 == 1 && b % 2 == 1, 1, '_'),
            FormatOp.Code => Inline(text, s, e, '`', 1, (a, b) => a == 1 && b == 1, 1, null),
            FormatOp.Strikethrough => Inline(text, s, e, '~', 2, (a, b) => a >= 2 && b >= 2, 2, null),
            FormatOp.Link => Link(text, s, e),
            FormatOp.Heading1 => HeadingOp(text, s, e, 1),
            FormatOp.Heading2 => HeadingOp(text, s, e, 2),
            FormatOp.Heading3 => HeadingOp(text, s, e, 3),
            FormatOp.Heading4 => HeadingOp(text, s, e, 4),
            FormatOp.Heading5 => HeadingOp(text, s, e, 5),
            FormatOp.Heading6 => HeadingOp(text, s, e, 6),
            FormatOp.HeadingCycle => HeadingOp(text, s, e, null),
            FormatOp.BulletList => BulletOp(text, s, e),
            FormatOp.TaskList => TaskOp(text, s, e),
            FormatOp.Quote => QuoteOp(text, s, e),
            FormatOp.Indent => IndentOp(text, s, e),
            FormatOp.Outdent => OutdentOp(text, s, e),
            _ => throw new ArgumentOutOfRangeException(nameof(op), op, "Unknown formatting command"),
        };
    }

    /// <summary>
    /// Typing <c>*</c>, <c>_</c>, <c>`</c> or <c>$</c> over a non-empty selection wraps it, selection kept on
    /// the original text; anything else — a caret, any other text — is null, and the keystroke is ordinary typing.
    /// </summary>
    public static FormatEdit? WrapTyped(string text, int selectionStart, int selectionEnd, string typed)
    {
        ArgumentNullException.ThrowIfNull(text);
        ArgumentNullException.ThrowIfNull(typed);
        var (s, e) = selectionStart <= selectionEnd ? (selectionStart, selectionEnd) : (selectionEnd, selectionStart);
        if (s == e) return null;
        if (typed is not ("*" or "_" or "`" or "$")) return null;
        return new FormatEdit(s, e, typed + text[s..e] + typed, s + 1, e + 1);
    }

    // ── Inline ──────────────────────────────────────────────────────────────────────────────

    static int RunBefore(string text, int p, char ch, int floor = 0)
    {
        var n = 0;
        while (p - n - 1 >= floor && text[p - n - 1] == ch) n++;
        return n;
    }

    static int RunAfter(string text, int p, char ch, int ceiling)
    {
        var n = 0;
        while (p + n < ceiling && text[p + n] == ch) n++;
        return n;
    }

    static (int A, int B) Trimmed(string text, int s, int e)
    {
        int a = s, b = e;
        while (a < b && IsBlankUnit(text[a])) a++;
        while (b > a && IsBlankUnit(text[b - 1])) b--;
        return (a, b);
    }

    static FormatEdit Inline(string text, int s, int e, char ch, int width, Func<int, int, bool> present, int remove, char? alternative)
    {
        var marker = new string(ch, width);

        if (s == e)
        {
            if (RunBefore(text, s, ch) == width && RunAfter(text, s, ch, text.Length) == width)
            {
                return new FormatEdit(s - width, s + width, string.Empty, s - width, s - width);
            }
            return new FormatEdit(s, s, marker + marker, s + width, s + width);
        }

        char[] markers = alternative is { } alt ? [ch, alt] : [ch];

        // 1. The selection carries the markers itself.
        foreach (var c in markers)
        {
            var lead = RunAfter(text, s, c, e);
            var trail = RunBefore(text, e, c, s);
            if (lead + trail >= e - s) continue;
            var isMain = c == ch;
            var here = isMain ? present(lead, trail) : lead == 1 && trail == 1;
            var count = isMain ? remove : 1;
            if (!here) continue;
            var inner = text[(s + count)..(e - count)];
            return new FormatEdit(s, e, inner, s, s + inner.Length);
        }

        // 2. The markers sit just outside the selection.
        foreach (var c in markers)
        {
            var before = RunBefore(text, s, c);
            var after = RunAfter(text, e, c, text.Length);
            var isMain = c == ch;
            var here = isMain ? present(before, after) : before == 1 && after == 1;
            var count = isMain ? remove : 1;
            if (!here) continue;
            var inner = text[s..e];
            return new FormatEdit(s - count, e + count, inner, s - count, s - count + inner.Length);
        }

        // 3. Wrap what is selected, without its surrounding blanks.
        var (a, b) = Trimmed(text, s, e);
        if (a == b) return new FormatEdit(s, s, marker + marker, s + width, s + width);
        return new FormatEdit(a, b, marker + text[a..b] + marker, a + width, b + width);
    }

    static bool StartsWithAsciiIgnoringCase(string text, string prefix)
    {
        if (text.Length < prefix.Length) return false;
        for (var i = 0; i < prefix.Length; i++)
        {
            var c = text[i];
            if (c is >= 'A' and <= 'Z') c = (char)(c + 32);
            if (c != prefix[i]) return false;
        }
        return true;
    }

    static FormatEdit Link(string text, int s, int e)
    {
        var (a, b) = Trimmed(text, s, e);
        if (a == b) return new FormatEdit(s, s, "[]()", s + 1, s + 1);
        var inner = text[a..b];
        var blank = false;
        foreach (var c in inner) if (IsBlankUnit(c)) blank = true;
        if (!blank && (StartsWithAsciiIgnoringCase(inner, "http://") || StartsWithAsciiIgnoringCase(inner, "https://")))
        {
            return new FormatEdit(a, b, "[](" + inner + ")", a + 1, a + 1);
        }
        var urlAt = a + 1 + inner.Length + 2;
        return new FormatEdit(a, b, "[" + inner + "](url)", urlAt, urlAt + 3);
    }

    // ── Lines ───────────────────────────────────────────────────────────────────────────────

    readonly record struct Line(int Start, int End);

    /// <summary>Replace <c>[At, At + Old)</c> of one line with <see cref="Text"/>.</summary>
    readonly record struct LineChange(int At, int Old, string Text);

    static Line LineAt(string text, int p)
    {
        var start = p;
        while (start > 0 && text[start - 1] != LF) start--;
        var end = p;
        while (end < text.Length && text[end] != LF) end++;
        return new Line(start, end);
    }

    static List<Line> TouchedLines(string text, int s, int e)
    {
        var first = LineAt(text, s);
        var lastPos = e;
        if (e > s && e > 0 && text[e - 1] == LF) lastPos = e - 1;
        var lines = new List<Line> { first };
        var current = first;
        while (current.End < lastPos)
        {
            current = LineAt(text, current.End + 1);
            lines.Add(current);
        }
        return lines;
    }

    static bool IsBlankLine(string line)
    {
        foreach (var c in line) if (c is not (SP or TAB)) return false;
        return true;
    }

    static int IndentEnd(string line)
    {
        var i = 0;
        while (i < line.Length && line[i] is SP or TAB) i++;
        return i;
    }

    static char At(string line, int i) => i >= 0 && i < line.Length ? line[i] : '\0';

    static bool IsDigit(char c) => c is >= '0' and <= '9';

    readonly record struct HeadingMarker(int At, int Level, int Length);

    static HeadingMarker? Heading(string line)
    {
        var i = 0;
        while (i < 3 && At(line, i) == SP) i++;
        var n = 0;
        while (At(line, i + n) == '#') n++;
        if (n is < 1 or > 6) return null;
        var after = i + n;
        if (after == line.Length) return new HeadingMarker(i, n, n);
        if (line[after] == SP) return new HeadingMarker(i, n, n + 1);
        return null;
    }

    enum ListKind { Bullet, Ordered }

    readonly record struct ListMarker(int At, ListKind Kind, bool Task, int ContentAt);

    static ListMarker? ListMarkerOf(string line)
    {
        var at = IndentEnd(line);
        var i = at;
        ListKind kind;
        var c = At(line, i);
        if (c is '-' or '*' or '+')
        {
            kind = ListKind.Bullet;
            i++;
        }
        else
        {
            var d = 0;
            while (d < 9 && IsDigit(At(line, i + d))) d++;
            if (d == 0) return null;
            var p = At(line, i + d);
            if (p is not ('.' or ')')) return null;
            kind = ListKind.Ordered;
            i += d + 1;
        }
        if (i == line.Length) return new ListMarker(at, kind, false, i);
        if (line[i] != SP) return null;
        if (i + 4 <= line.Length)
        {
            var box = line.Substring(i + 1, 3);
            if (box is "[ ]" or "[x]" or "[X]")
            {
                var after = i + 4;
                if (after == line.Length) return new ListMarker(at, kind, true, after);
                if (line[after] == SP) return new ListMarker(at, kind, true, after + 1);
            }
        }
        return new ListMarker(at, kind, false, i + 1);
    }

    readonly record struct QuoteMarker(int At, int Length);

    static QuoteMarker? QuoteOf(string line)
    {
        var i = 0;
        while (i < 3 && At(line, i) == SP) i++;
        if (At(line, i) != '>') return null;
        return new QuoteMarker(i, At(line, i + 1) == SP ? 2 : 1);
    }

    delegate LineChange?[] Plan(IReadOnlyList<string> lines, IReadOnlyList<bool> participating);

    static FormatEdit? ApplyLines(string text, int s, int e, Plan plan)
    {
        var lines = TouchedLines(text, s, e);
        var strings = lines.Select(l => text[l.Start..l.End]).ToList();
        var multi = lines.Count > 1;
        var participating = strings.Select(l => !(multi && IsBlankLine(l))).ToList();
        var changes = plan(strings, participating);
        if (changes.All(c => c is null || (c.Value.Old == 0 && c.Value.Text.Length == 0))) return null;

        int Map(int p)
        {
            var delta = 0;
            for (var k = 0; k < lines.Count; k++)
            {
                var change = changes[k];
                var line = lines[k];
                var lineDelta = change is { } c ? c.Text.Length - c.Old : 0;
                if (p > line.End)
                {
                    delta += lineDelta;
                    continue;
                }
                if (change is not { } ch) return p + delta;
                var a = line.Start + ch.At;
                if (p >= a + ch.Old) return p + delta + lineDelta;
                if (p <= a) return p + delta;
                return a + delta + ch.Text.Length;
            }
            return p + delta;
        }

        var output = new List<string>(strings.Count);
        for (var k = 0; k < strings.Count; k++)
        {
            var l = strings[k];
            output.Add(changes[k] is { } c ? string.Concat(l.AsSpan(0, c.At), c.Text, l.AsSpan(c.At + c.Old)) : l);
        }
        return new FormatEdit(lines[0].Start, lines[^1].End, string.Join(LF, output), Map(s), Map(e));
    }

    static LineChange? SetHeading(string line, int level)
    {
        if (Heading(line) is { } h)
        {
            if (level == 0) return new LineChange(h.At, h.Length, string.Empty);
            if (h.Level == level && h.Length == level + 1) return null;
            return new LineChange(h.At, h.Length, new string('#', level) + " ");
        }
        if (level == 0) return null;
        var indent = IndentEnd(line);
        var at = indent <= 3 && !line.AsSpan(0, indent).Contains(TAB) ? indent : 0;
        return new LineChange(at, 0, new string('#', level) + " ");
    }

    static FormatEdit? HeadingOp(string text, int s, int e, int? level) =>
        ApplyLines(text, s, e, (lines, on) =>
        {
            int target;
            if (level is null)
            {
                var first = -1;
                for (var k = 0; k < lines.Count; k++) if (on[k]) { first = k; break; }
                var current = first < 0 ? 0 : Heading(lines[first])?.Level ?? 0;
                target = current switch { 0 => 1, 1 => 2, 2 => 3, _ => 0 };
            }
            else
            {
                var all = true;
                for (var k = 0; k < lines.Count; k++) if (on[k] && Heading(lines[k])?.Level != level) all = false;
                target = all ? 0 : level.Value;
            }
            return lines.Select((l, k) => on[k] ? SetHeading(l, target) : null).ToArray();
        });

    static FormatEdit? BulletOp(string text, int s, int e) =>
        ApplyLines(text, s, e, (lines, on) =>
        {
            var all = true;
            for (var k = 0; k < lines.Count; k++)
            {
                if (!on[k]) continue;
                if (ListMarkerOf(lines[k]) is not { Kind: ListKind.Bullet, Task: false }) all = false;
            }
            return lines.Select((l, k) =>
            {
                if (!on[k]) return (LineChange?)null;
                var m = ListMarkerOf(l);
                if (all) return new LineChange(m!.Value.At, m.Value.ContentAt - m.Value.At, string.Empty);
                if (m is null) return new LineChange(IndentEnd(l), 0, "- ");
                if (m.Value.Task || m.Value.Kind == ListKind.Ordered) return new LineChange(m.Value.At, m.Value.ContentAt - m.Value.At, "- ");
                return null;
            }).ToArray();
        });

    static FormatEdit? TaskOp(string text, int s, int e) =>
        ApplyLines(text, s, e, (lines, on) =>
        {
            var all = true;
            for (var k = 0; k < lines.Count; k++) if (on[k] && ListMarkerOf(lines[k])?.Task != true) all = false;
            return lines.Select((l, k) =>
            {
                if (!on[k]) return (LineChange?)null;
                var m = ListMarkerOf(l);
                if (all) return new LineChange(m!.Value.At, m.Value.ContentAt - m.Value.At, string.Empty);
                if (m is null) return new LineChange(IndentEnd(l), 0, "- [ ] ");
                if (m.Value.Task) return null;
                if (m.Value.Kind == ListKind.Ordered) return new LineChange(m.Value.At, m.Value.ContentAt - m.Value.At, "- [ ] ");
                // A bullet: the box goes after its marker and space (a bare `-` gets its space too).
                return new LineChange(m.Value.At, m.Value.ContentAt - m.Value.At, l[m.Value.At] + " [ ] ");
            }).ToArray();
        });

    static FormatEdit? QuoteOp(string text, int s, int e)
    {
        var lines = TouchedLines(text, s, e);
        var strings = lines.Select(l => text[l.Start..l.End]).ToList();
        var multi = lines.Count > 1;
        // Blank lines do not decide "all quoted", but when quoting they get a bare `>`.
        var all = strings.All(l => (multi && IsBlankLine(l)) || QuoteOf(l) is not null);
        return ApplyLines(text, s, e, (ls, _) => ls.Select(l =>
        {
            if (all) return QuoteOf(l) is { } q ? new LineChange(q.At, q.Length, string.Empty) : (LineChange?)null;
            if (QuoteOf(l) is not null) return null;
            if (multi && IsBlankLine(l)) return new LineChange(0, 0, ">");
            return new LineChange(0, 0, "> ");
        }).ToArray());
    }

    static FormatEdit? IndentOp(string text, int s, int e) =>
        ApplyLines(text, s, e, (lines, on) => lines.Select((_, k) => on[k] ? new LineChange(0, 0, "  ") : (LineChange?)null).ToArray());

    static FormatEdit? OutdentOp(string text, int s, int e) =>
        ApplyLines(text, s, e, (lines, _) => lines.Select(l =>
        {
            if (At(l, 0) == TAB) return new LineChange(0, 1, string.Empty);
            var n = At(l, 0) == SP ? (At(l, 1) == SP ? 2 : 1) : 0;
            return n == 0 ? (LineChange?)null : new LineChange(0, n, string.Empty);
        }).ToArray());
}
